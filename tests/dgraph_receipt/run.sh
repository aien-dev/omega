#!/bin/sh
# tests/dgraph_receipt/run.sh TOOL JSON_CANON WORKDIR: host-only tests of tools/dgraph_receipt.c
# (aien-architecture#233 P1, spec docs/perf/DECODE_GRAPH_RECEIPT.md). No GPU, reads evidence/ only.
#   1. regenerate each golden receipt from its evidence run and compare byte for byte with fixtures/
#   2. the checker accepts every golden receipt (and the hand-written NOT_RUN one), json_canon agrees
#      it is strict JSON, and every evidence path exists in this tree
#   3. every negative fixture in negatives.txt is refused, for the reason named there, and differs
#      from the good receipt it was cut from (a negative identical to a good one proves nothing)
#   4. the generator refuses bad input (missing flag, log without settings, stats/log from two runs)
# Run from the repo root (the Makefile does). Exit 0 only when every case holds.
set -u
TOOL="${1:?tool}"; CANON="${2:?json_canon}"; WORK="${3:?workdir}"
T=tests/dgraph_receipt; F=$T/fixtures
rm -rf "$WORK"; mkdir -p "$WORK"
fails=0; cases=0
ok()  { cases=$((cases + 1)); echo "ok: $*"; }
bad() { cases=$((cases + 1)); fails=$((fails + 1)); echo "FAIL: $*"; }

MODEL="synthetic Qwen3-30B-A3B-shaped decode step, random weights"
PREC="FP8 e4m3 weights (qkv, o, gate_up, down), BF16 lm_head, f32 activations"
MODE="decode, one token per command list (omega_gpu_decode_graph_token), batch 1"

# golden 1: decode_graph main at omega main 710d438c (clean tree), uncached weights, prefetch off
R1=evidence/OWN30B-REQUAL-MAIN-710d438c-20261015/gates/decode_graph
gen_main() {
  "$TOOL" --run-dir "$R1" --stats "$R1/receipt-main.json" --log "$R1/main.log" --status HISTORICAL --repo aien-spark/omega \
    --model "$MODEL" --precision "$PREC" --mode "$MODE" --runner "tools/run_gpu_decode_graph_chip.sh EVIDENCE_DIR main" \
    --evidence evidence/OWN30B-REQUAL-MAIN-710d438c-20261015/NOTES.md "$@"
}
# golden 2: the same base, GPU-cached weights with the W-L2d prefetch on (independent launches)
R2=evidence/OWN30B-REQUAL-MAIN-710d438c-20261015/gates/l2d_prefetch
gen_prefetch() {
  "$TOOL" --run-dir "$R2" --stats "$R2/receipt-4-cached-prefetch.json" --log "$R2/4-cached-prefetch.log" --status HISTORICAL \
    --repo aien-spark/omega --model "$MODEL" --precision "$PREC" --mode "$MODE" \
    --runner "tools/run_gpu_l2d_prefetch_chip.sh EVIDENCE_DIR (run 4-cached-prefetch: --cached-weights --prefetch --reps 10)" \
    --evidence evidence/OWN30B-REQUAL-MAIN-710d438c-20261015/NOTES.md "$@"
}

# 1 + 2: golden receipts
for g in main prefetch; do
  golden="$F/good-historical-710d438c-$g.json"
  if "gen_$g" --out "$WORK/$g.json" 2> "$WORK/$g.err"; then
    if cmp -s "$WORK/$g.json" "$golden"; then ok "golden $g regenerated byte for byte from evidence"; else bad "golden $g differs from $golden"; diff "$golden" "$WORK/$g.json" | head -20; fi
  else bad "generator failed on golden $g: $(cat "$WORK/$g.err")"; fi
done
for good in "$F"/good-*.json; do
  if out=$("$TOOL" --check "$good" --evidence-root .); then ok "checker accepts $good"; else bad "checker refused $good: $out"; fi
  if "$CANON" --check < "$good"; then ok "json_canon: $good is strict JSON"; else bad "json_canon refused $good"; fi
done
# the receipts carry the evidence numbers unchanged (independent of the tool: grep both files)
for pair in "C_total:graph total_ns" "C_chip:graph chip_ns" "span_ns:stamped span_ns"; do
  key=${pair%%:*}
  want=$(grep -o "\"$key\":[0-9]*" "$R1/receipt-main.json" | head -n 1 | cut -d: -f2)
  case "$key" in C_total) f=total_ns ;; C_chip) f=chip_ns ;; *) f=span_ns ;; esac
  got=$(grep -o "\"$f\": [0-9]*" "$F/good-historical-710d438c-main.json" | head -n 1 | cut -d' ' -f2)
  if [ -n "$want" ] && [ "$want" = "$got" ]; then ok "${pair#*:} $got equals evidence $key"; else bad "${pair#*:} $got vs evidence $key $want"; fi
done

# 3: negative fixtures (file, the good receipt it was cut from, expected reason)
while IFS='|' read -r name base reason; do
  case "$name" in ''|'#'*) continue ;; esac
  n="$F/$name"
  if [ ! -f "$n" ]; then bad "negative $name missing"; continue; fi
  if cmp -s "$n" "$F/$base"; then bad "negative $name is identical to $base"; continue; fi
  out=$("$TOOL" --check "$n" --evidence-root .); rc=$?
  if [ $rc = 1 ] && printf '%s' "$out" | grep -qF -- "$reason"; then ok "refused $name ($reason)"
  else bad "negative $name: exit $rc, wanted 1 with \"$reason\", got: $out"; fi
done < "$T/negatives.txt"

# 4: generator refusals (nothing written)
"$TOOL" --run-dir "$R1" --stats "$R1/receipt-main.json" --log "$R1/main.log" --repo aien-spark/omega --model m --precision p --mode d \
  --runner r --out "$WORK/x1.json" 2> /dev/null
rc=$?; if [ $rc = 2 ] && [ ! -e "$WORK/x1.json" ]; then ok "generator: missing --status is a usage error"; else bad "generator: missing --status gave exit $rc"; fi
head -n 0 "$R1/main.log" > "$WORK/empty.log"
"$TOOL" --run-dir "$R1" --stats "$R1/receipt-main.json" --log "$WORK/empty.log" --status HISTORICAL --repo aien-spark/omega --model m \
  --precision p --mode d --runner r --out "$WORK/x3.json" 2> "$WORK/x3.err"
rc=$?; if [ $rc = 2 ] && [ ! -e "$WORK/x3.json" ] && grep -q 'dgraph prefetch' "$WORK/x3.err"; then ok "generator: log without the run's settings refused"; else bad "generator: settings-less log gave exit $rc"; fi
"$TOOL" --run-dir "$R1" --stats "$R1/receipt-main.json" --log "$R2/4-cached-prefetch.log" --status HISTORICAL --repo aien-spark/omega \
  --model m --precision p --mode d --runner r --out "$WORK/x4.json" 2> "$WORK/x4.err"
rc=$?; if [ $rc = 2 ] && [ ! -e "$WORK/x4.json" ] && grep -q 'not the same run' "$WORK/x4.err"; then ok "generator: stats and log from two runs refused"; else bad "generator: mixed runs gave exit $rc"; fi
gen_main --status TBD --out "$WORK/x5.json" 2> /dev/null
rc=$?
if [ $rc = 2 ]; then ok "generator: a repeated --status is a usage error"; else bad "generator: repeated --status gave exit $rc"; fi
"$TOOL" --run-dir "$R1" --stats "$R1/receipt-main.json" --log "$R1/main.log" --status DONE --repo aien-spark/omega --model m \
  --precision p --mode d --runner r --out "$WORK/x6.json" 2> "$WORK/x6.err"
rc=$?; if [ $rc = 1 ] && [ ! -e "$WORK/x6.json" ] && grep -q 'fails its own check' "$WORK/x6.err"; then ok "generator: status outside the enum never written"; else bad "generator: status DONE gave exit $rc"; fi

echo "dgraph_receipt tests: $cases cases, $fails failed"
[ $fails = 0 ]
